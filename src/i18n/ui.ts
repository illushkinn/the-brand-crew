/** Helper: get a nested value by dot path from a specific language */
export function getTranslation(lang: Lang, key: string): string {
  const dict = dictionaries[lang];
  const keys = key.split('.');
  let value: unknown = dict;
  for (const k of keys) {
    if (value && typeof value === 'object' && k in (value as Record<string, unknown>)) {
      value = (value as Record<string, unknown>)[k];
    } else {
      return key;
    }
  }
  return String(value ?? key);
}

/** Returns a bound `t(key)` function for the given language */
export function useTranslations(lang: Lang) {
  return (key: string): string => getTranslation(lang, key);
}
